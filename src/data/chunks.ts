// Tramos de nivel. Cada nivel se arma encadenando tramos (ver `game/level.ts`).
//
// Tramos horizontales: 15 filas. Contrato: la primera y la última columna tienen suelo en las filas 13-14
// y aire en las filas 9-12, así que cualquier orden de tramos se puede recorrer.
// Tramos de torre: 26 columnas con paredes a los lados; se apilan de abajo arriba. Tienen plataformas
// cada 3 filas contando desde abajo (la última fila y la fila 2 siempre tienen plataforma en el centro).
// Salas: 15 filas, cerradas, con una puerta D que vuelve al nivel.
//
// Leyenda:
//   .  aire                 #  suelo (cambia según el mundo)   X  bloque macizo     I  hielo
//   B  ladrillo rompible    ?  bloque premio (moneda)          Q  bloque premio (corazón)
//   i  bloque invisible (aparece al golpearlo desde abajo y suelta una moneda)
//   -  tablón (se atraviesa desde abajo)   =  vía     C  nube     v  hojas     V  tablón que se cae
//   ^  pinchos              ~  agua mala o lava                S  resorte           T  tronco (fondo)
//   o  moneda    g  gema (10 monedas)    h  corazón (cura)     d  adorno            t  antorcha
//   K  punto de control     G  salida               H  salida secreta              P  inicio
//   k  llave                L  cerradura (la abre una llave)
//   l  palanca              E  bloque rojo (macizo con la palanca apagada)   F  bloque azul (macizo encendida)
//   R  muro agrietado (3 golpes)          Y  muro falso (se atraviesa)
//   D  puerta a una sala    O  barra de fuego        A  cañón
//   m  plataforma móvil horizontal (3 casillas)               n  plataforma móvil vertical
//   a b c  monstruos de suelo · e  monstruo grande · f  volador · j  especial (según el mundo)
//   !  estalactita          %  bloque furioso
//   W  reja que se cierra al empezar el jefe                   Z  jefe

/** Tipos de nivel en los que encaja un tramo (letras). */
// L llanura · B bosque · D desierto · N nieve · C cueva · K castillo y fortaleza · S cielo · A agua · R vagoneta
export interface Chunk {
  rows: string[];
  tags: string;
  /** Exige doble salto: solo a partir del mundo 2. */
  hard?: boolean;
  /** Sala a la que lleva la puerta D del tramo. */
  room?: string;
}

const E = (w: number) => '.'.repeat(w);
/** Rellena con aire por arriba hasta tener 15 filas. */
function c(tags: string, rows: string[], opts: { hard?: boolean; room?: string } = {}): Chunk {
  const w = rows[0].length;
  const pad: string[] = [];
  for (let i = rows.length; i < 15; i++) pad.push(E(w));
  return { rows: [...pad, ...rows], tags, ...opts };
}
/** Tramo de torre (sin relleno). */
const t = (rows: string[], opts: { room?: string } = {}): Chunk => ({ rows, tags: 'T', ...opts });

