// Tramos de nivel. Cada nivel se arma encadenando tramos (ver `data/worlds.ts`).
// Todos miden 15 filas. Contrato: la primera y la última columna tienen suelo en las
// filas 13-14 y aire en las filas 0-12, así que cualquier orden de tramos se puede recorrer.
//
// Leyenda:
//   .  aire                 #  suelo (cambia según el mundo)   X  bloque macizo
//   B  ladrillo rompible    ?  bloque premio (moneda)          Q  bloque premio (corazón)
//   -  tablón (se atraviesa desde abajo)                       ^  pinchos
//   ~  agua (o lava en el castillo)                            S  resorte
//   o  moneda    g  gema (10 monedas)    h  corazón (cura)     d  adorno
//   K  punto de control     G  puerta de salida                P  inicio del jugador
//   m  plataforma móvil horizontal (3 casillas)               n  plataforma móvil vertical
//   a b c  monstruos de suelo (según el mundo)                f  monstruo volador
//   W  reja que se cierra al empezar el jefe                   Z  jefe

export interface Chunk {
  rows: string[];
  /** Exige doble salto para llegar a la salida (solo a partir del mundo 2). */
  hard?: boolean;
}

const E = (w: number) => '.'.repeat(w);
/** Rellena con aire por arriba hasta tener 15 filas. */
function chunk(rows: string[], hard = false): Chunk {
  const w = rows[0].length;
  const pad: string[] = [];
  for (let i = rows.length; i < 15; i++) pad.push(E(w));
  return { rows: [...pad, ...rows], hard };
}

